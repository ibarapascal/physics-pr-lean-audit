def _pp():
    from pandapower.create import (create_bus, create_empty_network, create_ext_grid,
                                   create_transformer_from_parameters, create_asymmetric_load)
    from pandapower.shortcircuit import calc_sc
    from pandapower.pf.runpp_3ph import runpp_3ph
    return dict(create_bus=create_bus, create_empty_network=create_empty_network,
                create_ext_grid=create_ext_grid,
                create_transformer_from_parameters=create_transformer_from_parameters,
                create_asymmetric_load=create_asymmetric_load, calc_sc=calc_sc, runpp_3ph=runpp_3ph)


def build_net(P, vg, p, rn, xn, with_load=False):
    net = P["create_empty_network"](sn_mva=p["sn_net"])
    bhv = P["create_bus"](net, vn_kv=p["vn_hv"])
    blv = P["create_bus"](net, vn_kv=p["vn_lv"])
    P["create_ext_grid"](net, bhv, vm_pu=1.0, s_sc_max_mva=p["s_sc"], s_sc_min_mva=p["s_sc"],
                         rx_max=0.1, rx_min=0.1, x0x_max=p["x0x"], x0x_min=p["x0x"],
                         r0x0_max=0.1, r0x0_min=0.1)
    P["create_transformer_from_parameters"](
        net, bhv, blv, sn_mva=p["sn_t"], vn_hv_kv=p["vn_hv"], vn_lv_kv=p["vn_lv"],
        vk_percent=p["vk"], vkr_percent=p["vkr"], pfe_kw=0.0, i0_percent=0.0,
        vector_group=vg, shift_degree=0.0, vk0_percent=p["vk"], vkr0_percent=p["vkr"],
        mag0_percent=p["mag0"], mag0_rx=p["mag0_rx"], si0_hv_partial=p["si"],
        rn_ohm=float(rn), xn_ohm=float(xn))
    if with_load:
        P["create_asymmetric_load"](net, blv, p_a_mw=0.3 * p["sn_t"], q_a_mvar=0.1 * p["sn_t"],
                                    p_b_mw=0.05 * p["sn_t"], q_b_mvar=0.0,
                                    p_c_mw=0.05 * p["sn_t"], q_c_mvar=0.0)
    return net, bhv, blv


def native_sc(P, vg, p, rn, xn, case):
    net, bhv, blv = build_net(P, vg, p, rn, xn)
    P["calc_sc"](net, fault="1ph", case=case)
    r = net.res_bus_sc
    out = {}
    for name, b in (("hv", bhv), ("lv", blv)):
        out[name] = {"z0": complex(float(r.at[b, "rk0_ohm"]), float(r.at[b, "xk0_ohm"])),
                     "ikss_ka": float(r.at[b, "ikss_ka"])}
    from pandapower.pypower.idx_bus_sc import C_MAX
    out["cmax_lv"] = float(np.real(net._ppc["bus"][net._pd2ppc_lookups["bus"][blv], C_MAX]))
    return out


def native_pf3ph_z0_lv(P, p, rn, xn):
    """After runpp_3ph, build the zero-sequence Ybus from net._ppc0 and return the LV-bus driving-point impedance (per unit) and the three-phase voltages."""
    from pandapower.pypower.makeYbus import makeYbus
    net, bhv, blv = build_net(P, "Dyn", p, rn, xn, with_load=True)
    P["runpp_3ph"](net)
    ppc0 = net._ppc0
    ybus, _, _ = makeYbus(ppc0["baseMVA"], ppc0["bus"], ppc0["branch"])
    zbus = np.linalg.inv(ybus.toarray())
    l = int(net._pd2ppc_lookups["bus"][blv])
    vm = {ph: float(net.res_bus_3ph.at[blv, "vm_%s_pu" % ph]) for ph in "abc"}
    return complex(zbus[l, l]), vm


def cj(z):
    return [float(np.real(z)), float(np.imag(z))] if z is not None else None


def rel(a, b):
    if a is None or b is None:
        return None
    den = max(abs(b), 1e-300)
    return float(abs(a - b) / den)


