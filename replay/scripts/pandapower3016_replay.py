def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--n", type=int, default=40, help="number of random parameter sets")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=None, help="JSON output path (default: stdout)")
    args = ap.parse_args()

    P = _pp()
    import pandapower
    rng = random.Random(args.seed)

    sc_cases, pf_cases = [], []
    for _ in range(args.n):
        p = sample_params(rng)
        rn, xn = sample_zn(rng)
        for vg in SC_GROUPS:
            for case in ("max", "min"):
                sc_cases.append(run_sc_case(P, vg, p, rn, xn, case))
        pf_cases.append(run_pf3ph_case(P, p, rn, xn))

    summary = {"n_sc": len(sc_cases), "n_pf3ph": len(pf_cases), "by_vg": {}, "pf3ph": {}}
    for r in sc_cases:
        d = summary["by_vg"].setdefault(r["vg"], {})
        d[r["verdict"]] = d.get(r["verdict"], 0) + 1
    for r in pf_cases:
        summary["pf3ph"][r["verdict"]] = summary["pf3ph"].get(r["verdict"], 0) + 1

    out = {
        "meta": {"pr": 3016, "merge_sha": MERGE_SHA,
                 "pandapower_version": getattr(pandapower, "__version__", "?"),
                 "n": args.n, "seed": args.seed, "rtol": RTOL,
                 "lean_file": "lean/PhysAudit/Pandapower3016.lean"},
        "sc_cases": sc_cases,
        "pf3ph_cases": pf_cases,
        "counterexamples": counterexamples(P),
        "summary": summary,
    }
    text = json.dumps(out, indent=1, ensure_ascii=False, default=str)
    if args.out:
        with open(args.out, "w") as f:
            f.write(text)
        print(json.dumps(summary, indent=1, ensure_ascii=False))
    else:
        sys.stdout.write(text + "\n")


if __name__ == "__main__":
    main()
