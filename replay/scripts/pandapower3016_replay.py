def lean_tap(vn_t, vn_b, sn_net, mode):
    """tapLv / tapHv: pd2ppc_zero.py:253-254, 269-270."""
    s = 3.0 * sn_net if mode == "pf_3ph" else sn_net
    return (vn_t / vn_b) ** 2 * s


def lean_zsc_rsc(vk0, vkr0, sn_t, tap_corr):
    """zSc / rSc: :273-274."""
    return vk0 / 100.0 / sn_t * tap_corr, vkr0 / 100.0 / sn_t * tap_corr


def lean_z0k_bare(vk0, vkr0, sn_t, tap_corr, par=1.0):
    """z0kBare: :277, :282."""
    z, r = lean_zsc_rsc(vk0, vkr0, sn_t, tap_corr)
    x = math.copysign(1.0, z) * math.sqrt(z * z - r * r) if z != 0 else 0.0
    return complex(r, x) / par


def lean_z0mag(vk0, vkr0, sn_t, tap_corr, mag0_ratio, mag0_rx, par=1.0):
    """z0mag: :337-342 (z_sc does not include Z_N)."""
    z_sc, _ = lean_zsc_rsc(vk0, vkr0, sn_t, tap_corr)
    zm = z_sc * mag0_ratio
    xm = zm / math.sqrt(mag0_rx ** 2 + 1)
    rm = xm * mag0_rx
    return complex(rm / par, xm / par)


def lean_zn_pu(zn, vn_earth, sn_net):
    """zNpu: :324 -- uses net.sn_mva in every mode."""
    return 3 * zn / (vn_earth ** 2 / sn_net)


def zbase(mode, vn, sn_net):
    """zBase: sc uses vn²/sn, pf_3ph uses vn²/(3·sn)."""
    return vn ** 2 / (3 * sn_net) if mode == "pf_3ph" else vn ** 2 / sn_net


def lean_kt(vk, vkr, cmax, case):
    """ktIEC: build_branch.py:1586-1597 (xt·sn = sqrt(vk²−vkr²)/100)."""
    if case != "max":
        return 1.0
    xt_sn = math.sqrt(vk ** 2 - vkr ** 2) / 100.0
    return 0.95 * cmax / (1 + 0.6 * xt_sn)


def lean_T_parts(si, z0k, zm):
    """tz1 / tz2 / tzT: :350-353."""
    z1 = si * z0k
    z2 = (1 - si) * z0k
    return z1, z2, z1 * z2 + z2 * zm + z1 * zm


EARTHED_HV = ("ynd", "yny", "ynyn", "znyn", "znd", "zny", "zd")
ZIGZAG = ("znyn", "znd", "zny", "zd")
ZN_LIST = ("dyn", "ynd", "yyn", "ynyn", "yny", "yzn", "znyn", "znd", "zny", "zd")
HV_GROUPS = ("ynd", "yny", "ynyn", "znyn", "znd", "zny", "zd")   # compared on the HV bus
LV_GROUPS = ("dyn", "yyn", "yzn")                                  # compared on the LV bus


def lean_sc_prediction(vg, p, zn, kt):
    """Measured quantity (Ω) predicted by the Lean transcription (code behavior, sc mode, default π model).

    LV vector groups return the LV-bus zero-sequence impedance; HV vector groups return the branch impedance after stripping the external grid (LV floating). Zd and ZNd share the same formula (C0).
    """
    g = vg.lower()
    sn = p["sn_net"]
    tap_corr = lean_tap(p["vn_hv"] if g in ("ynd", "yny") else p["vn_lv"],
                        p["vn_hv"] if g in ("ynd", "yny") else p["vn_lv"], sn, "sc")
    # bus voltage = rated voltage, so tap_corr = sn
    zb = lean_z0k_bare(p["vk"], p["vkr"], p["sn_t"], tap_corr)
    zm = lean_z0mag(p["vk"], p["vkr"], p["sn_t"], tap_corr, p["mag0"] / 100.0, p["mag0_rx"])
    vn_e = p["vn_hv"] if g in EARTHED_HV else p["vn_lv"]
    znpu = lean_zn_pu(zn, vn_e, sn) if (abs(zn) > 0 and g in ZN_LIST) else 0j
    z0k = zb * kt
    if g not in ZIGZAG:
        z0k = z0k + znpu
    si = p["si"]
    if g == "dyn":                                   # dyn_pi_lv
        return zbase("sc", p["vn_lv"], sn) * z0k
    if g == "yyn":                                   # yyn_pi_lv
        return zbase("sc", p["vn_lv"], sn) * (zm + z0k)
    if g == "yzn":                                   # yzn_lv
        _, z2, _ = lean_T_parts(si, z0k, zm)
        return zbase("sc", p["vn_lv"], sn) * (z2 + zm) / (1.1547 * sn)
    if g == "ynd":                                   # ynd_pi_hv
        return zbase("sc", p["vn_hv"], sn) * z0k
    if g == "yny":                                   # yny_pi_hv
        return zbase("sc", p["vn_hv"], sn) * (zm + z0k)
    if g == "ynyn":                                  # ynyn_hv
        z1, _, _ = lean_T_parts(si, z0k, zm)
        return zbase("sc", p["vn_hv"], sn) * (z1 + zm)
    if g in ("znyn", "znd", "zny", "zd"):            # zig_hv
        return zbase("sc", p["vn_hv"], sn) * (si * z0k + znpu)
    raise ValueError(vg)


def lean_pf3ph_dyn_lv_pu(p, zn):
    """B2: LV zero-sequence impedance (per unit, pf_3ph base) of Dyn under pf_3ph with the T model."""
    sn = p["sn_net"]
    tap_corr = lean_tap(p["vn_lv"], p["vn_lv"], sn, "pf_3ph")
    zb = lean_z0k_bare(p["vk"], p["vkr"], p["sn_t"], tap_corr)
    zm = lean_z0mag(p["vk"], p["vkr"], p["sn_t"], tap_corr, p["mag0"] / 100.0, p["mag0_rx"])
    znpu = lean_zn_pu(zn, p["vn_lv"], sn) if abs(zn) > 0 else 0j
    z0k = zb + znpu
    si = p["si"]
    return (1 - si) * z0k + si * z0k * zm / (si * z0k + zm)


