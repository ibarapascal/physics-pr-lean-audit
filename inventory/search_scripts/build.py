# Stage 2: consolidate search state into candidates, verify signatures, map commit hits to merged PRs, fetch file lists/patches.
import json, re, subprocess, os, csv, time, sys
D = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(D)  # inventory/ (candidates.csv is written there)
S = json.load(open(os.path.join(D,'state.json')))
if os.path.exists(os.path.join(D,'state2.json')): S.update(json.load(open(os.path.join(D,'state2.json'))))
os.makedirs(os.path.join(D,'patches'), exist_ok=True)
CACHE = os.path.join(D,'api_cache.json')
cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
ncalls = 0
def api(path, paginate=False):
    global ncalls
    key = path + ('|p' if paginate else '')
    if key in cache: return cache[key]
    for attempt in range(6):
        args = ['gh','api',path] + (['--paginate'] if paginate else [])
        p = subprocess.run(args, capture_output=True, text=True); ncalls += 1
        if p.returncode == 0:
            txt = p.stdout
            if paginate:
                txt = re.sub(r'\]\s*\[', ',', txt.strip())
            try: d = json.loads(txt)
            except Exception: d = {'error':'parse'}
            cache[key] = d
            if ncalls % 100 == 0: json.dump(cache, open(CACHE,'w'))
            return d
        e = p.stderr.lower()
        if 'rate limit' in e or '403' in e: time.sleep(60); continue
        if '404' in e or '410' in e: cache[key] = {'error':'404'}; return cache[key]
        time.sleep(5)
    return {'error':'fail'}
SIG = [('claude', re.compile(r'Generated with \[?Claude Code|Co-Authored-By:\s*Claude|claude\.ai/code|noreply@anthropic\.com', re.I)),
       ('devin', re.compile(r'Devin run|app\.devin\.ai|devin\.ai/sessions|devin-ai-integration', re.I)),
       ('codex', re.compile(r'chatgpt\.com/codex|Codex task|Generated by Codex|chatgpt-codex-connector', re.I)),
       ('copilot', re.compile(r'copilot-swe-agent|Co-authored-by:\s*Copilot', re.I)),
       ('jules', re.compile(r'google-labs-jules|jules\.google', re.I))]
def sig(text):
    for n, rx in SIG:
        m = rx.search(text or '')
        if m:
            s = max(0, m.start()-20); return f'{n}: "' + re.sub(r'\s+',' ', text[s:m.end()+30]).strip() + '"'
    return None
cands = {}   # (repo,number) -> dict
rejected = []
def add(repo, num, url, title, author, merged_at, evid, query):
    k = (repo, num)
    c = cands.setdefault(k, {'repo':repo,'number':num,'url':url,'title':title,'author':author,'merged_at':merged_at,'evid':[],'queries':[]})
    if evid not in c['evid']: c['evid'].append(evid)
    if query not in c['queries']: c['queries'].append(query)
commit_hits = []
for key, ent in S.items():
    repo, qname = key.split('|',1)
    if not ent.get('done'): continue
    if qname.startswith('author:'):
        for it in ent['items']:
            add(repo, it['number'], it['url'], it['title'], it['author'], it['merged_at'], f'author account {it["author"]}', qname)
    elif qname.startswith('text:'):
        for it in ent['items']:
            e = sig(it['body']+'\n'+it['title'])
            if e: add(repo, it['number'], it['url'], it['title'], it['author'], it['merged_at'], 'PR body: '+e, qname)
            else: rejected.append((repo, it['number'], it['url'], qname))  # may be verified through commits below
    elif qname.startswith('commit:'):
        for it in ent['items']:
            e = sig(it['msg'])
            if e: commit_hits.append((repo, it['sha'], e, qname))
            else: rejected.append((repo, it['sha'], it['url'], qname+' (commit msg lacks signature)'))
print('direct cands', len(cands), 'unverified text hits', len(rejected), 'commit hits', len(commit_hits), flush=True)
# verify unverified text hits via PR commits
still = []
for repo, num, url, qname in [r for r in rejected if isinstance(r[1], int)]:
    if (repo,num) in cands: continue
    pr = api(f'repos/{repo}/pulls/{num}')
    cm = api(f'repos/{repo}/pulls/{num}/commits?per_page=100')
    ev = None
    if isinstance(cm, list):
        for c in cm:
            ev = sig(c['commit']['message'])
            if ev: break
    if ev and pr.get('merged_at'):
        add(repo, num, url, pr['title'], pr['user']['login'], pr['merged_at'], 'PR commit message: '+ev, qname)
    else:
        still.append((repo, num, url, qname))
# map commit hits to PRs
for repo, sha, e, qname in commit_hits:
    prs = api(f'repos/{repo}/commits/{sha}/pulls')
    if not isinstance(prs, list) or not prs:
        still.append((repo, sha, '', qname+' (commit has no PR)')); continue
    for pr in prs:
        if pr.get('merged_at') and '2025-01-01' <= pr['merged_at'][:10] <= '2026-10-16':
            add(repo, pr['number'], pr['html_url'], pr['title'], pr['user']['login'], pr['merged_at'], f'commit {sha[:8]} message: '+e, qname)
        else:
            still.append((repo, pr['number'], pr['html_url'], qname+' (commit PR not merged in window)'))
# merged_at window filter & file lists
rows = []
for (repo, num), c in sorted(cands.items()):
    if not c['merged_at'] or not ('2025-01-01' <= c['merged_at'][:10] <= '2026-10-16'):
        pr = api(f'repos/{repo}/pulls/{num}'); c['merged_at'] = pr.get('merged_at')
        if not c['merged_at'] or not ('2025-01-01' <= c['merged_at'][:10] <= '2026-10-16'): continue
    pf = os.path.join(D,'patches',f'{repo.replace("/","__")}__{num}.json')
    if os.path.exists(pf): files = json.load(open(pf))
    else:
        files = api(f'repos/{repo}/pulls/{num}/files?per_page=100', paginate=True)
        cache.pop(f'repos/{repo}/pulls/{num}/files?per_page=100|p', None)
        if isinstance(files, list): json.dump(files, open(pf,'w'))
    c['files'] = files if isinstance(files, list) else []
    rows.append(c)
json.dump(cache, open(CACHE,'w'))
with open(os.path.join(OUT,'candidates.csv'),'w',newline='') as f:
    w = csv.writer(f); w.writerow(['repo','number','url','title','author','merged_at','signature_evidence','files_changed','query'])
    for c in rows:
        names = [x['filename'] for x in c['files']]
        fs = ';'.join(names[:30]) + (f';...(total {len(names)} files)' if len(names) > 30 else '')
        w.writerow([c['repo'],c['number'],c['url'],c['title'],c['author'],c['merged_at'][:10],' | '.join(c['evid'])[:400],fs,' ; '.join(c['queries'])])
json.dump([{k:v for k,v in c.items()} for c in rows], open(os.path.join(D,'cands_full.json'),'w'))
json.dump(still, open(os.path.join(D,'unverified.json'),'w'))
print('final candidates', len(rows), 'unverified/dropped', len(still), 'api calls', ncalls)
